import 'dart:typed_data';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import 'reports_local_dao.dart';

/// Builds a styled project-monthly PDF report using the `pdf` package.
class PdfReportBuilder {
  const PdfReportBuilder._();

  static Future<Uint8List> build(ProjectReportData data) async {
    final doc = pw.Document(
      title: '${data.projectName} – Monthly Report',
      author: 'FieldOps',
    );

    final headerStyle = pw.TextStyle(
      fontSize: 22,
      fontWeight: pw.FontWeight.bold,
      color: PdfColors.blue800,
    );
    final sectionStyle = pw.TextStyle(
      fontSize: 13,
      fontWeight: pw.FontWeight.bold,
      color: PdfColors.grey800,
    );
    final labelStyle = pw.TextStyle(fontSize: 11, color: PdfColors.grey700);
    final valueStyle = pw.TextStyle(
      fontSize: 14,
      fontWeight: pw.FontWeight.bold,
    );

    final month = _monthLabel(data.periodStart, data.periodEnd);
    final progressPct = (data.progressPercent * 100).round();

    doc.addPage(
      pw.Page(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(40),
        build: (context) => pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            // ── Header ─────────────────────────────────────────────────────
            pw.Text('FIELDOPS', style: headerStyle),
            pw.SizedBox(height: 4),
            pw.Text(
              'PROJECT MONTHLY REPORT',
              style: pw.TextStyle(
                fontSize: 13,
                color: PdfColors.grey600,
                letterSpacing: 1.2,
              ),
            ),
            pw.Divider(color: PdfColors.blue200, thickness: 1.5),
            pw.SizedBox(height: 8),
            pw.Text(
              data.projectName,
              style: pw.TextStyle(fontSize: 18, fontWeight: pw.FontWeight.bold),
            ),
            pw.Text(
              month,
              style: pw.TextStyle(fontSize: 12, color: PdfColors.grey600),
            ),
            pw.SizedBox(height: 24),

            // ── Beneficiary stats ──────────────────────────────────────────
            pw.Text('Beneficiaries', style: sectionStyle),
            pw.SizedBox(height: 8),
            _statsRow([
              _Stat('Total', '${data.beneficiaries}', labelStyle, valueStyle),
              _Stat('Male', '${data.male}', labelStyle, valueStyle),
              _Stat('Female', '${data.female}', labelStyle, valueStyle),
            ]),
            pw.SizedBox(height: 20),

            // ── Activity stats ─────────────────────────────────────────────
            pw.Text('Reach', style: sectionStyle),
            pw.SizedBox(height: 8),
            _statsRow([
              _Stat(
                'Communities',
                '${data.communities}',
                labelStyle,
                valueStyle,
              ),
              _Stat('Activities', '${data.activities}', labelStyle, valueStyle),
            ]),
            pw.SizedBox(height: 20),

            // ── Progress bar ───────────────────────────────────────────────
            pw.Text('Project Progress', style: sectionStyle),
            pw.SizedBox(height: 8),
            pw.Row(
              children: [
                pw.Expanded(
                  flex: (data.progressPercent * 100).round().clamp(1, 99),
                  child: pw.Container(
                    height: 16,
                    decoration: pw.BoxDecoration(
                      color: PdfColors.blue700,
                      borderRadius: const pw.BorderRadius.all(
                        pw.Radius.circular(3),
                      ),
                    ),
                  ),
                ),
                pw.Expanded(
                  flex: (100 - (data.progressPercent * 100).round()).clamp(
                    1,
                    99,
                  ),
                  child: pw.Container(
                    height: 16,
                    decoration: pw.BoxDecoration(
                      color: PdfColors.grey200,
                      borderRadius: const pw.BorderRadius.all(
                        pw.Radius.circular(3),
                      ),
                    ),
                  ),
                ),
              ],
            ),
            pw.SizedBox(height: 4),
            pw.Text(
              '$progressPct% target achieved',
              style: pw.TextStyle(fontSize: 11, color: PdfColors.grey600),
            ),
            pw.Spacer(),

            // ── Footer ─────────────────────────────────────────────────────
            pw.Divider(color: PdfColors.grey300),
            pw.Text(
              'Generated by FieldOps Mobile  •  ${_formattedDate(DateTime.now())}',
              style: pw.TextStyle(fontSize: 9, color: PdfColors.grey500),
            ),
          ],
        ),
      ),
    );

    return Uint8List.fromList(await doc.save());
  }

  // ---------------------------------------------------------------------------
  // Helpers
  // ---------------------------------------------------------------------------

  static pw.Widget _statsRow(List<_Stat> stats) {
    return pw.Row(
      children: stats
          .map(
            (s) => pw.Expanded(
              child: pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.start,
                children: [
                  pw.Text(s.label, style: s.labelStyle),
                  pw.SizedBox(height: 2),
                  pw.Text(s.value, style: s.valueStyle),
                ],
              ),
            ),
          )
          .toList(),
    );
  }

  static String _monthLabel(DateTime from, DateTime to) {
    const months = [
      'January',
      'February',
      'March',
      'April',
      'May',
      'June',
      'July',
      'August',
      'September',
      'October',
      'November',
      'December',
    ];
    if (from.month == to.month && from.year == to.year) {
      return '${months[from.month - 1]} ${from.year}';
    }
    return '${months[from.month - 1]} – ${months[to.month - 1]} ${to.year}';
  }

  static String _formattedDate(DateTime d) =>
      '${d.day.toString().padLeft(2, '0')}/'
      '${d.month.toString().padLeft(2, '0')}/'
      '${d.year}';
}

class _Stat {
  const _Stat(this.label, this.value, this.labelStyle, this.valueStyle);
  final String label;
  final String value;
  final pw.TextStyle labelStyle;
  final pw.TextStyle valueStyle;
}
